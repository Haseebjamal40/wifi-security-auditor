"""
Report Generator Module
Generates comprehensive Markdown, JSON, and HTML reports summarizing lab configuration,
session notes, tool availability, command references, and result analysis.
"""

import json
import os
import logging
from html import escape
from datetime import datetime

logger = logging.getLogger('WiFiLab.ReportGenerator')

def generate_markdown_report(session_data: dict, output_path: str) -> str:
    """Build a structured Markdown report."""
    now = datetime.now().strftime('%Y-%m-%d %H:%M:%S')
    md = []
    md.append("# Wi-Fi Security Educational Lab Report")
    md.append(f"**Generated:** {now}  ")
    session_id = session_data.get('session_id', 'N/A')
    md.append(f"**Session ID:** `{session_id}`\n")

    md.append("## 1. Executive Summary")
    md.append("This report documents the configuration, environment status, command reference queries, ")
    md.append("and user-submitted log analysis for the educational Wi-Fi security lab framework.\n")

    md.append("## 2. Lab Configuration Parameters")
    config = session_data.get('config', {})
    md.append("| Parameter | Value |")
    md.append("| --- | --- |")
    for k, v in config.items():
        md.append(f"| **{k}** | `{v}` |")
    md.append("\n")

    md.append("## 3. Dependency Check Results")
    deps = session_data.get('dependencies', {})
    total = deps.get('total_tools', 0)
    installed = deps.get('installed_count', 0)
    missing = deps.get('missing_count', 0)
    md.append(f"- **Total Required Tools:** {total}")
    md.append(f"- **Installed:** {installed}")
    md.append(f"- **Missing:** {missing}\n")
    
    details = deps.get('details', {})
    if details:
        md.append("| Tool | Status | Binary Path |")
        md.append("| --- | --- | --- |")
        for tool, info in details.items():
            st = 'Installed' if info['installed'] else 'Missing'
            pth = info['path'] if info['path'] else 'N/A'
            md.append(f"| `{tool}` | {st} | `{pth}` |")
        md.append("\n")

    md.append("## 4. Parsed Results & Log Analysis")
    results = session_data.get('analysis_results', {})
    if results:
        res_str = json.dumps(results, indent=2)
        md.append(f"```json\n{res_str}\n```\n")
    else:
        md.append("No external log outputs analyzed during this session.\n")

    md.append("## 5. Lab Notes")
    notes = session_data.get('notes', [])
    if notes:
        for note in notes:
            title = note.get('title', 'Untitled')
            c_text = note.get('content', '')
            md.append(f"### Note: {title}")
            md.append(f"{c_text}\n")
    else:
        md.append("No session notes recorded.\n")

    md.append("---")
    md.append("*Generated by Wi-Fi Security Lab Automation Framework (Defensive & Educational Mode)*")

    report_content = '\n'.join(md)
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(report_content)
    logger.info(f"Generated Markdown report at {output_path}")
    return output_path

def generate_json_report(session_data: dict, output_path: str) -> str:
    """Export session details as raw JSON."""
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(session_data, f, indent=2)
    logger.info(f"Generated JSON report at {output_path}")
    return output_path

def generate_html_report(session_data: dict, output_path: str) -> str:
    """Generate a stylized HTML report."""
    now = datetime.now().strftime('%Y-%m-%d %H:%M:%S')
    config = session_data.get('config', {})
    deps = session_data.get('dependencies', {})
    session_id = session_data.get('session_id', 'N/A')
    
    rows = []
    for k, v in config.items():
        rows.append(
            f"<tr><td>{escape(str(k))}</td><td><code>{escape(str(v))}</code></td></tr>"
        )
    rows_html = '\n'.join(rows)

    inst_cnt = deps.get('installed_count', 0)
    tot_cnt = deps.get('total_tools', 0)

    html_content = f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <title>Wi-Fi Security Educational Lab Report</title>
    <style>
        body {{ font-family: sans-serif; margin: 30px; background: #f8f9fa; color: #212529; }}
        h1, h2 {{ color: #0d6efd; }}
        .container {{ max-width: 900px; margin: auto; background: white; padding: 25px; border-radius: 8px; }}
        table {{ width: 100%; border-collapse: collapse; margin-bottom: 20px; }}
        th, td {{ padding: 10px; border: 1px solid #dee2e6; text-align: left; }}
        th {{ background: #e9ecef; }}
        code {{ background: #e9ecef; padding: 2px 5px; border-radius: 4px; }}
    </style>
</head>
<body>
    <div class="container">
        <h1>Wi-Fi Security Educational Lab Report</h1>
        <p><strong>Generated:</strong> {escape(now)}<br><strong>Session ID:</strong> <code>{escape(str(session_id))}</code></p>
        
        <h2>Lab Parameters</h2>
        <table>
            <tr><th>Parameter</th><th>Value</th></tr>
            {rows_html}
        </table>
        
        <h2>Dependency Check</h2>
        <p>Installed: <strong>{inst_cnt}</strong> / Total: <strong>{tot_cnt}</strong></p>
        
        <h2>Session Summary</h2>
        <p>Lab framework execution complete. All data recorded strictly in non-offensive educational mode.</p>
    </div>
</body>
</html>
"""
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(html_content)
    logger.info(f"Generated HTML report at {output_path}")
    return output_path
